package com.example.imperfect.feature.analysis.domain.interpretation

fun skinHealthDescription(
    severity: String,
    percent: Int
): String {

    return when (severity.lowercase()) {

        "mild" -> when {
            percent >= 85 ->
                "Кожа находится в хорошем состоянии. Воспалений практически нет, наблюдается стабильное восстановление кожного барьера."

            percent >= 70 ->
                "Лёгкие единичные высыпания. Состояние в целом стабильное, кожа хорошо реагирует на уход."

            percent >= 50 ->
                "Присутствуют небольшие воспаления. Рекомендуется продолжать регулярный уход и наблюдать динамику."

            else ->
                "Отмечаются лёгкие высыпания. Состояние не критичное, но требует регулярного ухода и контроля."
        }

        "moderate" -> when {
            percent >= 80 ->
                "Наблюдается положительная динамика. Состояние кожи улучшается, воспаления постепенно уменьшаются."

            percent >= 60 ->
                "Средний уровень высыпаний. Состояние нестабильное, но контролируемое при регулярном уходе."

            percent >= 40 ->
                "Умеренное количество воспалений. Кожа требует более внимательного ухода и коррекции режима."

            else ->
                "Выраженные воспалительные процессы. Рекомендуется усиленный уход и наблюдение за динамикой состояния."
        }

        "severe" -> when {
            percent >= 70 ->
                "Состояние начинает стабилизироваться, однако сохраняются выраженные признаки воспаления."

            percent >= 50 ->
                "Тяжёлое состояние кожи с активными воспалениями. Требуется системный подход к уходу."

            percent >= 30 ->
                "Высокая активность высыпаний. Кожа находится в стрессовом состоянии, необходим усиленный контроль."

            else ->
                "Критическое состояние кожи с выраженными воспалительными процессами. Рекомендуется консультация специалиста."
        }

        else ->
            "Недостаточно данных для точной оценки состояния кожи. Рекомендуется провести повторный анализ."
    }
}